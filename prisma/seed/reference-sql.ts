import type { CompetitionPlan } from "./seed";

// The reference tables reach production through migrations, never through a seed run from a workstation: this turns
// part of the seed's plan into idempotent SQL, applied by `prisma migrate deploy` on deployment. Every row is inserted
// with ON CONFLICT DO NOTHING on its natural key (code, slug, initial club and squad slot), so a database already
// seeded keeps its rows, and its ids. Ids are drawn by gen_random_uuid(): they differ from one database to another, as
// the seed's cuids do, and no draw ever depends on them.

/** A SQL string literal: single quotes doubled. */
function literal(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

/** A Prisma DateTime as stored by PostgreSQL (timestamp(3), UTC): « 1997-02-25 00:00:00.000 ». */
function timestamp(date: Date): string {
  return literal(date.toISOString().replace("T", " ").replace("Z", ""));
}

function values(rows: readonly string[][]): string {
  return rows.map((row) => `  (${row.join(", ")})`).join(",\n");
}

/** Idempotent SQL inserting the competitions of a plan, their clubs and the clubs' players. */
export function referenceInsertSql(plan: readonly CompetitionPlan[]): string {
  const competitions = plan.map(({ competition }) => [
    literal(competition.code),
    literal(competition.name),
    literal(competition.country),
    String(competition.tier),
  ]);
  const clubs = plan.flatMap(({ competition, clubs }) =>
    clubs.map((club) => [
      literal(competition.code),
      literal(club.slug),
      literal(club.name),
      literal(competition.country),
      String(club.initialRank),
      literal(club.colors.primary),
      literal(club.colors.secondary),
    ]),
  );
  const players = plan.flatMap(({ clubs }) =>
    clubs.flatMap((club) =>
      club.players.map((player) => [
        literal(club.slug),
        String(player.squadSlot),
        literal(player.firstName),
        literal(player.lastName),
        timestamp(player.birthDate),
        literal(player.nationality),
        literal(player.position),
      ]),
    ),
  );

  return `INSERT INTO "Competition" ("id", "code", "name", "country", "tier")
SELECT gen_random_uuid()::text, v.code, v.name, v.country, v.tier
FROM (VALUES
${values(competitions)}
) AS v (code, name, country, tier)
ON CONFLICT ("code") DO NOTHING;

INSERT INTO "Club" ("id", "slug", "name", "country", "initialRank", "primaryColor", "secondaryColor", "competitionId")
SELECT gen_random_uuid()::text, v.slug, v.name, v.country, v.initial_rank, v.primary_color, v.secondary_color, c."id"
FROM (VALUES
${values(clubs)}
) AS v (competition, slug, name, country, initial_rank, primary_color, secondary_color)
JOIN "Competition" c ON c."code" = v.competition
ON CONFLICT ("slug") DO NOTHING;

INSERT INTO "Player" ("id", "initialClubId", "squadSlot", "firstName", "lastName", "birthDate", "nationality", "position")
SELECT gen_random_uuid()::text, k."id", v.squad_slot, v.first_name, v.last_name, v.birth_date::timestamp(3), v.nationality, v.position::"Position"
FROM (VALUES
${values(players)}
) AS v (club, squad_slot, first_name, last_name, birth_date, nationality, position)
JOIN "Club" k ON k."slug" = v.club
ON CONFLICT ("initialClubId", "squadSlot") DO NOTHING;
`;
}

/** The migration bringing the second divisions (tier 2) to a database: prisma/migrations/…_second_divisions. */
export function secondDivisionsMigrationSql(plan: readonly CompetitionPlan[]): string {
  const secondDivisions = plan.filter(({ competition }) => competition.tier === 2);
  const clubCount = secondDivisions.reduce((count, { clubs }) => count + clubs.length, 0);
  const playerCount = secondDivisions.reduce(
    (count, { clubs }) => count + clubs.reduce((sum, club) => sum + club.players.length, 0),
    0,
  );
  return `-- The second divisions of the 2024-25 source season: ${secondDivisions.length} competitions, ${clubCount} clubs, ${playerCount} players.
-- Generated by scripts/generate-reference-migration.ts from the seed's plan (prisma/seed), never edited by hand:
-- prisma/seed/reference-sql.test.ts checks it against the generator. Idempotent: a database seeded with them keeps its
-- rows, and \`npm run db:seed\` after it writes no player.
${referenceInsertSql(secondDivisions)}`;
}
